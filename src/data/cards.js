export const CARDS = RAW.map((card) => ({
  ...card,
  slug: slugify(card.name),
  image: `https://gfx.tarot.com/images/site/decks/english-magic/full_size/${card.id}.jpg`,
}));

export const getCardBySlug = (slug) => CARDS.find((c) => c.slug === slug);

/** Same card all day long, a different one tomorrow. */
export function getCardOfTheDay(date = new Date()) {
  const key = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  return CARDS[(Math.imul(key, 2654435761) >>> 0) % CARDS.length];
}

